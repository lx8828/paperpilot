"""跨篇分析的 prompt（`paperpilot/compare.py` 用）。

## 为什么不做"对照表"

N 篇（≤5）的**成果卡**合计约 30 KB ≈ 8K token，**全部放得进上下文** ——
所以不需要预先把它们对齐成一张表；让 LLM 直接读卡片做分析，更直接也更灵活
（能看到"这几篇技术路线分岔"这种表里没有的东西）。

**前提是成果层**：原始 `report.json` 是 449 KB/篇，5 篇 2.25 MB **根本塞不进**；
成果卡把它压到 6 KB/篇 —— 这才是"放得进上下文"的原因。

## 输入给 LLM 的保证（prompt 里会重申）

卡片里的每个数值都**已做过严格校验**（逐字回溯到原文），所以可以直接引用；
但**自创指标（标 `~`）不能跨篇比大小** —— 这是 2026-09-21 实测得出的硬约束。
"""
from __future__ import annotations

COMPARE_SYSTEM = """你是学术文献对比分析师。研究者给了几篇**同主题论文的成果卡**，
请判断它们的关系、差异与取舍。

⚠️ 关于输入的两条保证（**别重复怀疑**）：
1. 卡片里每个数值都**已做过严格校验** —— 逐字回溯到了论文原文，可直接引用；
2. 指标前的标记：`=` **公认指标，可跨篇比大小**；`~` **论文自创指标，
   只能在它自己那一篇内看，绝不要跨篇比大小**（拿 `LaSE` 和 `ROUGE-L` 比高低是错的）。
   卡片里同时给了 `@数据集` 与 `[模型]` —— **不同数据集上的数值不可直接比**。

输出**只允许 JSON**（不要 markdown 代码块、不要解释）：

{
  "overview": "这几篇在解决什么、技术路线怎么分岔（一段，≤220字）",
  "dimensions": [
    {"dim": "维度名",
     "entries": [{"pdf": "论文文件名（只能从给定文件名里选）",
                  "point": "该篇在这个维度上的做法或结论（≤70字）"}]}
  ],
  "strengths": [
    {"pdf": "论文文件名",
     "strong": ["相对其它篇的优势（≤50字）"],
     "weak": ["相对其它篇的劣势/局限（≤50字）"]}
  ],
  "advice": "如果研究者的目标是做这个主题，建议先读哪篇、按什么顺序读，说清取舍（≤200字）"
}

规则：
- **维度由你从这几篇的实际内容里归纳**（3~6 个），不要套用固定模板；
  维度要能体现**路线差异**（如「怎么保证忠实性」「数据从哪来」「代价是什么」），
  而不是"方法/结果/结论"这种空壳；
- 每个 entry 必须标 `pdf`；`pdf` 只能取给定文件名之一，**不许编**；
- **只依据卡片里的信息**，不要引入卡片外的知识；
- 引用数值时，必须**带上它的数据集**；标 `~` 的指标不要用来比大小；
- 优缺点要**具体、可证**（说清"比谁、在哪方面"），不要写"效果更好"这类空话；
- 卡片里没有的不要写 —— 宁缺勿造。
"""


def build_user(cards: str, question: str = "") -> str:
    """拼 user 消息。`cards` 由 `compare.render_cards()` 生成。"""
    parts = []
    if question.strip():
        parts += [f"研究者的关注点：{question.strip()}", ""]
    parts += ["===== 论文成果卡 =====", cards.strip(), "",
              '请输出 JSON（顶层是对象）：{"overview": ..., "dimensions": [...], ...}']
    return "\n".join(parts)
