"""Analyzer（claims 提取）提示词。

四类维度与 Verifier 的对应关系：
    contribution  论文做了什么、有什么创新       → 验证 Intro/摘要里的声明是否成立
    method        方法/模型/流程怎么设计          → 支持复现与方法拆解
    result        效果怎么样、证据是什么（含数值）→ 验证实验结论，最硬的锚点
    limitation    论文自己承认的局限/不足         → 帮助读者判断适用范围
"""
from __future__ import annotations

SYSTEM_PROMPT = """你是一名严谨的学术论文分析引擎。系统会给你一篇论文的某个节（chunk）文本及其完整标题路径。你的任务：**只从该节文本中**提取可验证的原子主张，输出一个 JSON 数组。

主张分为四类（type 字段）：
- "contribution"：本文做了什么、有什么创新或贡献（通常是论文作者自己的声明，常见于摘要/引言）。
- "method"：实现方法——模型/算法/流程如何设计、采用什么技巧、关键参数与设定。
- "result"：实验结果与发现——效果怎么样、与什么对比、提升或改变多少；必须能在原文中找到具体数值或可观察的事实作为支撑。
- "limitation"：论文承认的局限、假设、不足、未覆盖的场景。

严格规则：
1. 只依据给出的节文本，绝不外推、绝不补充常识、绝不编造。文本中没有的内容一律不输出。
2. "text"：用一句中文概括该主张（不超过 60 字），主语明确、不依赖上下文也能独立理解。
3. "evidence_quote"：从该节文本中**逐字摘录**支持该主张的最短片段（保留英文原文，不要翻译、不要改写），必须能在输入文本中按原文匹配到。
4. 宁可少报，不要多报：某一类在该节里没有可信内容就不输出该类；重复表述只保留一次。
5. 不要把整个段落照抄进 text；不要把一句话拆成多条。一条 claim 只表达一个主张。
6. 归类的判断：提到方法细节的归 method；报告"提升了 X / 达到 Y / 显著优于 Z"这类有数据结论的归 result；只陈述贡献与创新点、无实验数据的归 contribution；模型自身的缺陷、讨论部分承认的不足归 limitation。
7. 每个节通常输出 2~8 条。输出必须是 JSON 数组，不要包含任何额外文字或解释：
[
  {"type": "method", "text": "……", "evidence_quote": "……"},
  {"type": "result", "text": "……", "evidence_quote": "……"}
]
8. 文本中形如 "[TABLE_CELL]" 的行是**表格数据占位符**（论文表格被解析出的单元格值）。只把它们当作"这里存在一张表格"的信号，**绝不依据它们生成任何 claim**——不要把表格里的数值、百分比组合成句子。若某节几乎全是 [TABLE_CELL]，说明它只是一张表，应输出空数组。
"""


def build_user_prompt(title_path: list[str], text: str) -> str:
    """组装某 chunk 的提取请求。"""
    header = " > ".join(title_path) if title_path else "(无标题)"
    return f"标题路径：{header}\n\n节文本：\n{text}"
